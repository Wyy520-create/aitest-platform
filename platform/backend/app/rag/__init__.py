"""RAG 模块：BM25 检索 + 知识库 + 问答链 + 质量评测。

REFUSE_THRESHOLD 放包级常量：检索层(评测器)与问答链共用，
且评测器不因此拉进 requests/LLM 依赖——CI 可零依赖直跑。
"""
# 拒答阈值：作用于「得分率」= BM25 绝对分 / 该查询理论满分（见 bm25.py
# 的 ideal_score），而不是绝对分——绝对分与查询长度正相关，短查询会被
# 误杀（实测：8 字查询 raw=4.1 与拒答类 raw=4.1 重叠，绝对阈值无解）。
# 取值依据（评测集实测分布）：拒答类得分率 ≤ 0.046，正常类 ≥ 0.070，
# 阈值取间隔带中间，两侧各留余量。
REFUSE_THRESHOLD = 0.055
